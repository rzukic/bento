    }

    private ModelJson Normalize(string json)
    {
        var parsed = ModelJsonSerializer.Parse(json);
        var validation = _validator.Validate(parsed);
        Assert.True(validation.IsValid, string.Join(Environment.NewLine, validation.Errors.Select(e => e.Message)));
        return validation.NormalizedModel;
    }

    private static async Task<SqliteConnection> OpenSqliteAsync()
    {
        var conn = new SqliteConnection("Data Source=:memory:");
        await conn.OpenAsync();
        using var pragma = conn.CreateCommand();
        pragma.CommandText = "PRAGMA foreign_keys=ON;";
        await pragma.ExecuteNonQueryAsync();
        return conn;
    }

    private static async Task ExecuteStatementsAsync(SqliteConnection conn, IEnumerable<string> statements)
    {
        foreach (var statement in statements)
        {
            using var cmd = conn.CreateCommand();
            cmd.CommandText = statement;
            await cmd.ExecuteNonQueryAsync();
        }
    }

    private static async Task<int> CountTablesAsync(SqliteConnection conn, params string[] tableNames)
    {
        using var cmd = conn.CreateCommand();
        var names = string.Join(", ", tableNames.Select(n => $"'{n}'"));
        cmd.CommandText = $"SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name IN ({names});";
        return Convert.ToInt32(await cmd.ExecuteScalarAsync());
    }

    private static async Task<int> CountIndexesAsync(SqliteConnection conn, string indexName)
    {
        using var cmd = conn.CreateCommand();
        cmd.CommandText = $"SELECT COUNT(*) FROM sqlite_master WHERE type = 'index' AND name = '{indexName}';";
        return Convert.ToInt32(await cmd.ExecuteScalarAsync());
    }

    private static async Task<bool> TableExistsAsync(SqliteConnection conn, string tableName)
    {
        using var cmd = conn.CreateCommand();
        cmd.CommandText = "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = $name;";
        cmd.Parameters.AddWithValue("$name", tableName);
        return Convert.ToInt32(await cmd.ExecuteScalarAsync()) == 1;
    }

    private static async Task<IReadOnlyList<string>> GetTableColumnsAsync(SqliteConnection conn, string tableName)
    {
        using var cmd = conn.CreateCommand();
        cmd.CommandText = $"PRAGMA table_info(\"{tableName}\");";

        var columns = new List<string>();
        await using var reader = await cmd.ExecuteReaderAsync();
        while (await reader.ReadAsync())
        {
            columns.Add(reader.GetString(1));
        }

        return columns;
    }
