    [Fact]
    public void Generate_Postgres_ProducesExpectedSql_ForCommonChanges()
    {
        var oldModel = Normalize("""
            {
              "version": 1,
              "tables": [
                {
                  "name": "orders",
                  "columns": [
                    { "name": "id", "type": "integer", "primaryKey": true, "nullable": false },
                    { "name": "total", "type": "float", "nullable": true },
                    { "name": "legacy_code", "type": "text" }
                  ],
                  "indexes": []
                }
              ],
              "relations": []
            }
            """);

        var newModel = Normalize("""
            {
              "version": 2,
              "tables": [
                {
                  "name": "orders",
                  "columns": [
                    { "name": "id", "type": "integer", "primaryKey": true, "nullable": false },
                    { "name": "customer_id", "type": "reference", "references": "customers" },
                    { "name": "total", "type": "integer", "nullable": false, "unique": true }
                  ],
                  "indexes": []
                },
                {
                  "name": "customers",
                  "columns": [
                    { "name": "id", "type": "integer", "primaryKey": true, "nullable": false },
                    { "name": "name", "type": "text", "nullable": false }
                  ],
                  "indexes": []
                }
              ],
              "relations": [
                { "name": "customer_orders", "type": "1:N", "from": "customers", "to": "orders", "column": "customer_id" }
              ]
            }
            """);

        var changes = _diff.Diff(oldModel, newModel);
        var generator = new MigrationGenerator(new DatabaseConfig { Provider = DatabaseProvider.Postgres });

        var plan = generator.Generate(oldModel, newModel, changes);
        var sql = string.Join("\n", plan.SqlUp);

        Assert.Contains("CREATE TABLE \"customers\"", sql);
        Assert.Contains("\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql);
        Assert.Contains("ADD COLUMN \"customer_id\" BIGINT REFERENCES \"customers\"(\"id\")", sql);
        Assert.Contains("DROP COLUMN \"legacy_code\"", sql);
        Assert.Contains("ALTER COLUMN \"total\" TYPE BIGINT USING CAST(\"total\" AS BIGINT)", sql);
        Assert.Contains("ALTER COLUMN \"total\" SET NOT NULL", sql);
        Assert.Contains("CREATE UNIQUE INDEX \"ux_orders_total\"", sql);
        Assert.True(plan.IsDestructive);
        Assert.NotEmpty(plan.SqlDown);
    }

