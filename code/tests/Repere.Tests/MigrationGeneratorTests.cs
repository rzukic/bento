    [Fact]
    public async Task Generate_Sqlite_RebuildPlan_ExecutesAndRollsBack()
    {
        var oldModel = Normalize("""
            {
              "version": 1,
              "tables": [
                {
                  "name": "orders",
                  "columns": [
                    { "name": "id", "type": "integer", "primaryKey": true, "nullable": false },
                    { "name": "legacy_code", "type": "text" },
                    { "name": "total", "type": "float", "nullable": true }
                  ],
                  "indexes": []
                }
              ],
              "relations": []
            }
            """);

        var newModel = Normalize("""
            {
              "version": 2,
              "tables": [
                {
                  "name": "orders",
                  "columns": [
                    { "name": "id", "type": "integer", "primaryKey": true, "nullable": false },
                    { "name": "amount", "renamedFrom": "total", "type": "integer", "nullable": false, "default": 0 },
                    { "name": "status", "type": "text", "nullable": false, "default": "draft" }
                  ],
                  "indexes": [
                    { "name": "idx_orders_status", "columns": ["status"], "unique": false }
                  ]
                }
              ],
              "relations": []
            }
            """);

        var sqliteGenerator = new MigrationGenerator(new DatabaseConfig { Provider = DatabaseProvider.Sqlite });
        await using var conn = await OpenSqliteAsync();

        var setupPlan = sqliteGenerator.Generate(Normalize("""{"version":1,"tables":[],"relations":[]}"""), oldModel, _diff.Diff(Normalize("""{"version":1,"tables":[],"relations":[]}"""), oldModel));
        await ExecuteStatementsAsync(conn, setupPlan.SqlUp);

        using (var insert = conn.CreateCommand())
        {
            insert.CommandText = """
                INSERT INTO "orders" ("legacy_code", "total")
                VALUES ('A-100', 12.75);
                """;
            await insert.ExecuteNonQueryAsync();
        }

        var changes = _diff.Diff(oldModel, newModel);
        var plan = sqliteGenerator.Generate(oldModel, newModel, changes);

        await ExecuteStatementsAsync(conn, plan.SqlUp);

        using (var query = conn.CreateCommand())
        {
            query.CommandText = """
                SELECT "amount", "status"
                FROM "orders"
                LIMIT 1;
                """;
            await using var reader = await query.ExecuteReaderAsync();
            Assert.True(await reader.ReadAsync());
            Assert.Equal(12L, reader.GetInt64(0));
            Assert.Equal("draft", reader.GetString(1));
        }

        Assert.Equal(1, await CountIndexesAsync(conn, "idx_orders_status"));

        await ExecuteStatementsAsync(conn, plan.SqlDown);

        using (var rollbackQuery = conn.CreateCommand())
        {
            rollbackQuery.CommandText = """
                SELECT "legacy_code", "total"
                FROM "orders"
                LIMIT 1;
                """;
            await using var reader = await rollbackQuery.ExecuteReaderAsync();
            Assert.True(await reader.ReadAsync());
            Assert.True(reader.IsDBNull(0));
            Assert.Equal(12.0, reader.GetDouble(1));
        }
    }

